import * as THREE from 'three';
import {MeshBVH} from 'three-mesh-bvh';
import assert from 'node:assert/strict';
import {vertexContact} from './vertex-contact.js';
const entry=g=>{g.computeBoundingBox();g.boundsTree=new MeshBVH(g);return{geometry:g,box:g.boundingBox}};
const a=entry(new THREE.BoxGeometry(1,.018,.24).rotateZ(Math.PI/4));
const shifted=x=>entry(new THREE.BoxGeometry(1,.018,.24).translate(x,0,0).rotateZ(Math.PI/4));
assert(vertexContact(a,shifted(1),.00005),'Angled end face contact');
assert(!vertexContact(a,shifted(1.001),.00005),'A one millimetre gap is not contact');
assert(!vertexContact(a,shifted(4),.00005),'Remote coplanar faces are not contact');
console.log('Angled contacts and real gaps distinguished');
